function help() {
  console.log(`Hermes + WorkBuddy AI + Magpie + 币安钱包入门包
  node starter.mjs install [--dry-run] [--skip-hermes]
  node starter.mjs workbuddy-login [--region intl|cn]
  node starter.mjs magpie-ui          打开 Magpie 本地页面并保持网关运行
  node starter.mjs models             查看模型 ID（不发起模型推理）
  node starter.mjs set-model workbuddy-ai/实际模型ID
  node starter.mjs agent              启动本项目的 Hermes
  node starter.mjs wallet-login       币安扫码登录，无交易
  node starter.mjs wallet-status      查询连接状态
  node starter.mjs wallet-address     查看地址
  node starter.mjs quote --amount 0.0001 --token 0x完整合约
  node starter.mjs doctor             检查环境，不发交易或模型请求
  node starter.mjs baw <官方CLI参数>   原样调用币安CLI；写操作会真实签名/交易
  所有命令可加 --proxy http://127.0.0.1:你的端口；不改变系统设置。
  免费模型额度不等于免费交易。详情见 README.md。`);
}

try {
  const command = args.shift() || 'help';
  if (command === 'help' || command === '--help') help();
  else if (command === 'install') await install();
  else if (command === 'doctor') await doctor();
  else {
    ensureInstalled();
    switch (command) {
      case 'workbuddy-login': {
        const provider = workbuddyProvider(take('--region', 'intl'));
        console.log('添加 Magpie 社区 WorkBuddy 插件；不是腾讯或币安官方桥接。请在厂商页面登录本人的账号。');
        await callMagpie(['plugin', 'add', VERSIONS.workbuddyPlugin], true);
        await callMagpie(['plugin', 'login', provider, '1'], true);
        console.log('登录流程结束。下一步打开 magpie-ui，核对账号、额度和可用模型。');
        break;
      }
      case 'magpie-ui': await callMagpie(['web'], true); break;
      case 'models': await callMagpie(['models'], true); break;
      case 'set-model': await setModel(args[0]); break;
      case 'wallet-login': await walletLogin(); break;
      case 'wallet-status': console.log(redact(await callBaw(['wallet', 'status', '--json']))); break;
      case 'wallet-address': console.log(redact(await callBaw(['wallet', 'address', '--json']))); break;
      case 'quote': {
        const amount = validateAmount(take('--amount'));
        const token = validateToken(take('--token'));
        console.log(await callBaw(['market-order', 'quote', '--fromTokenQty', amount,
          '--fromToken', '0xEeeeeEeeeEeEeeEeEeEeeEEEeeeeEeeeeeeeEEeE', '--toToken', token,
          '--binanceChainId', '56', '--slippage', '1', '--json']));
        break;
      }
      case 'agent': {
        if (!existsSync(stateFile)) throw new Error('请先登录 WorkBuddy、查看 models，然后 set-model。');
        const launch = await hermesLauncher();
        await run(launch.file, [...launch.prefix, ...args], { env, cwd: ROOT, inherit: true });
        break;
      }
      case 'baw': {
        if (!args.length || args.some(a => /^--(?:debug|verbose|log)/i.test(a))) throw new Error('请传入官方 CLI 命令，不使用调试日志参数。');
        if (!args.includes('--json')) args.push('--json');
        console.log(redact(await callBaw(args))); break;
      }
      default: throw new Error(`未知命令 ${command}。运行 node starter.mjs help。`);
    }
  }
} catch (error) { console.error(redact(error.message)); process.exitCode = 1; }
