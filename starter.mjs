  console.log(`Node ${process.versions.node}；${process.platform}/${process.arch}`);
  console.log(`代理：${proxy ? '当前进程使用已配置代理（不显示地址）' : '未配置'}；本地网关直连。`);
  console.log(`Magpie 文件：${existsSync(magpie) ? '已安装' : '缺失'}`);
  console.log(`币安 CLI：${existsSync(bawEntry) ? '已安装' : '缺失'}`);
