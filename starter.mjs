#!/usr/bin/env node
import { existsSync } from 'node:fs';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawnSync } from 'node:child_process';
import { assetName, childEnvironment, download, downloadVerified, findNpmCli, hermesModelSelection, installPlan,
  parseWindowsLauncher, powershellExecutable, redact, run, selectSkillEntries, validateAmount, validateModel, validateToken, verifyGitBlob,
  windowsSystemProxy, workbuddyProvider, writePreserving } from './lib/core.mjs';

const ROOT = dirname(fileURLToPath(import.meta.url));
const VERSIONS = JSON.parse(await readFile(join(ROOT, 'versions.json'), 'utf8'));
const [major, minor] = process.versions.node.split('.').map(Number);
if (major < 24 || (major === 24 && minor < 5)) {
  console.error('请先从 https://nodejs.org/ 安装 Node.js 24 LTS（至少 24.5），然后重开终端。');
  process.exit(1);
}
const args = process.argv.slice(2);
function take(name, fallback = '') {
  const index = args.indexOf(name);
  if (index < 0) return fallback;
  const value = args[index + 1];
  if (!value || value.startsWith('--')) throw new Error(`${name} 缺少值。`);
  args.splice(index, 2); return value;
}
const explicitProxy = take('--proxy');
const proxy = explicitProxy || process.env.HTTPS_PROXY || process.env.https_proxy || windowsSystemProxy();
const env = childEnvironment(ROOT, proxy);
// Node reads proxy configuration when it starts. Re-enter once, without a shell.
if (proxy && !process.execArgv.includes('--use-env-proxy')) {
  const result = spawnSync(process.execPath, ['--use-env-proxy', fileURLToPath(import.meta.url), ...args],
    { env, stdio: 'inherit', windowsHide: true });
  if (result.error) { console.error(redact(result.error.message)); process.exit(1); }
  process.exit(result.status ?? 1);
}
const runtime = join(ROOT, '.runtime');
const magpie = join(runtime, 'bin', process.platform === 'win32' ? 'magpie.exe' : 'magpie');
const bawEntry = join(runtime, 'npm', 'node_modules', '@binance', 'agentic-wallet', 'dist', 'index.js');
const stateFile = join(runtime, 'starter-state.json');
function ensureInstalled() {
  if (!existsSync(magpie) || !existsSync(bawEntry)) throw new Error('尚未安装，请先运行 node starter.mjs install。');
}
const callMagpie = (a, inherit = false) => run(magpie, a, { env, cwd: ROOT, inherit });
const callBaw = (a, inherit = false) => run(process.execPath, [bawEntry, ...a], { env, cwd: ROOT, inherit });

async function installSkills() {
  const { repo, commit, names } = VERSIONS.skills;
  if (!/^[0-9a-f]{40}$/.test(commit)) throw new Error('技能必须固定到提交。');
  const tree = JSON.parse((await download(`https://api.github.com/repos/${repo}/git/trees/${commit}?recursive=1`, 8 * 1024 * 1024)).toString());
  const entries = selectSkillEntries(tree, names);
  for (const f of entries) {
    const bytes = await download(`https://raw.githubusercontent.com/${repo}/${commit}/${f.path}`, 2 * 1024 * 1024);
    verifyGitBlob(bytes, f.sha);
    await writePreserving(join(env.HERMES_HOME, 'skills', f.name, f.relative), bytes);
  }
  console.log(`已校验并安装 ${names.length} 个官方技能（${entries.length} 个文件）。`);
}

async function hermesLauncher() {
  const bin = join(env.HERMES_HOME, 'bin');
  if (process.platform === 'win32') {
    // Prefer the native executable when supplied by the upstream runtime.
    const direct = join(bin, 'hermes.exe');
    if (existsSync(direct)) return { file: direct, prefix: [] };
    const ps = join(bin, 'hermes.ps1');
    if (existsSync(ps)) return { file: powershellExecutable(env), prefix: ['-NoProfile', '-ExecutionPolicy', 'Bypass', '-File', ps] };
    // Upstream source runtime entry is generated by PM; inspect only its launcher, never secrets.
    const cmd = join(bin, 'hermes.cmd');
    if (existsSync(cmd)) {
      const text = await readFile(cmd, 'utf8');
      const launch = parseWindowsLauncher(text);
      if (existsSync(launch.file)) return launch;
    }
  } else {
    const candidates = [join(env.HERMES_HOME, 'bin', 'hermes'), join(process.env.HOME || '', '.local', 'bin', 'hermes')];
    for (const file of candidates) if (existsSync(file)) return { file, prefix: [] };
  }
  throw new Error('未找到 Hermes 启动器。运行 node starter.mjs install，或查看 docs/TROUBLESHOOTING.md。');
}

async function installHermes() {
  const marker = join(runtime, 'hermes-install-complete');
  if (existsSync(marker)) { console.log('检测到本项目 Hermes 安装标记，保留已有安装。'); return; }
  const suffix = process.platform === 'win32' ? 'ps1' : 'sh';
  const item = VERSIONS.hermesInstallers[suffix];
  const installer = join(runtime, 'downloads', `hermes-install.${suffix}`);
  await downloadVerified(item.url, item.sha256, installer);
  console.log('正在运行 Hermes 官方稳定版安装器；首次需要下载运行环境，可能耗时较长。');
  const source = join(runtime, 'hermes-source');
  if (process.platform === 'win32') {
    const hermesEnv = { ...env };
    // Windows PowerShell cannot load PowerShell 7's modules from an inherited PSModulePath.
    if (powershellExecutable(env) === 'powershell.exe') delete hermesEnv.PSModulePath;
    await run(powershellExecutable(env), ['-NoProfile', '-ExecutionPolicy', 'Bypass', '-File', installer,
      '-Channel', 'stable', '-HermesHome', env.HERMES_HOME, '-InstallDir', source,
      '-NonInteractive', '-SkipBrowser', '-SkipComputerUse'], { env: hermesEnv, cwd: ROOT, inherit: true });
  } else {
    await run('bash', [installer, '--channel', 'stable', '--hermes-home', env.HERMES_HOME,
      '--dir', source, '--non-interactive', '--skip-browser', '--skip-computer-use'], { env, cwd: ROOT, inherit: true });
  }
  const launch = await hermesLauncher();
  await run(launch.file, [...launch.prefix, '--version'], { env, cwd: ROOT });
  await writeFile(marker, 'official stable installer completed\n', { mode: 0o600 });
}

async function install() {
  const skip = args.includes('--skip-hermes');
  const plan = installPlan(VERSIONS, process.platform, process.arch, skip);
  console.log(JSON.stringify(plan, null, 2));
  if (args.includes('--dry-run')) return;
  await mkdir(runtime, { recursive: true });
  const asset = VERSIONS.magpie.assets[assetName()];
  await downloadVerified(asset.url, asset.sha256, magpie);
  console.log('Magpie 文件 SHA-256 校验通过。');
  console.log('正在安装固定版本的币安钱包 CLI（仅本项目目录）。');
  await run(process.execPath, [findNpmCli(env), 'install', '--prefix', join(runtime, 'npm'),
    '--no-save', '--package-lock=false', '--no-audit', '--no-fund',
    ...Object.entries(VERSIONS.npm).map(([name, version]) => `${name}@${version}`)],
    { env, cwd: ROOT, inherit: true });
  if (!skip) await installHermes();
  await installSkills();
  console.log(redact(await callBaw(['cli-check', '--required-version', VERSIONS.npm['@binance/agentic-wallet'], '--json'])));
  console.log('\n安装完成。下一步：node starter.mjs workbuddy-login');
}

async function openLogin(url) {
  const parsed = new URL(url);
  if (parsed.protocol !== 'https:' || !(parsed.hostname === 'binance.com' || parsed.hostname.endsWith('.binance.com'))) {
    throw new Error('登录 URL 不属于 binance.com，已停止自动打开。');
  }
  try {
    if (process.platform === 'win32') await run('rundll32.exe', ['url.dll,FileProtocolHandler', url], { env });
    else await run(process.platform === 'darwin' ? 'open' : 'xdg-open', [url], { env });
  } catch { console.log('未能自动打开浏览器，请使用上面显示的完整链接。'); }
}

async function walletLogin() {
  const response = JSON.parse(await callBaw(['auth', 'signin', '--json']));
  if (!response.success) throw new Error(JSON.stringify(response.error));
  if (response.data.status !== 'ALREADY_CONNECTED') {
    const { pairingCode, urlForWeb, qrCodeId } = response.data;
    if (!pairingCode || !urlForWeb || !/^[0-9a-f-]{36}$/i.test(qrCodeId || '')) throw new Error('登录响应字段不完整。');
    console.log(`币安配对码：${pairingCode}\n登录链接：${urlForWeb}\n请在币安 App 中核对配对码并确认。验证会保持运行。`);
    await openLogin(urlForWeb);
    const verified = JSON.parse(await callBaw(['auth', 'verify', '--qrCodeId', qrCodeId, '--json']));
    if (!verified.success) throw new Error(JSON.stringify(verified.error));
  }
  const status = JSON.parse(await callBaw(['wallet', 'status', '--json']));
  if (status.data?.status !== 'CONNECTED') throw new Error('本机钱包尚未 CONNECTED，请重新运行 wallet-login。');
  await writeFile(join(runtime, 'wallet-connected'), 'connected via official CLI\n', { mode: 0o600 });
  console.log('钱包已连接。登录凭据由官方 CLI 保存，可能使用系统凭据管理器；勿分享 .runtime/baw 或导出登录数据。');
}

async function setModel(model) {
  validateModel(model);
  await mkdir(runtime, { recursive: true });
  console.log('仅配置本项目的 Hermes 钱包助手。');
  await callMagpie(hermesModelSelection(model), true);
  const launch = await hermesLauncher();
  const provider = await run(launch.file, [...launch.prefix, 'config', 'get', 'model.provider'], { env, cwd: ROOT });
  if (provider.trim() !== 'magpie') throw new Error('Hermes 未指向 Magpie，已停止；请检查 Magpie 兼容性。');
  await writeFile(stateFile, JSON.stringify({ model }, null, 2) + '\n', { mode: 0o600 });
  console.log('已选择模型。先运行 node starter.mjs magpie-ui 并保持窗口，再运行 node starter.mjs agent。');
}

